#!/usr/bin/env python3
"""Count how often each dictionary word occurs as a word in general Chinese text.

The input is plain UTF-8 text, a file or a member of a zip archive written
archive.zip!member: Cassotis IME uses the general text its character LM was
trained on (the three general corpora, not its fiction). Every simplified
word of two characters or more, and the simplified form of every traditional
word, is a fixed pattern of one ripgrep pass, longest first. ripgrep reports
the leftmost match and prefers the earlier pattern at one position, so a word
inside a longer dictionary word is no occurrence: 化为 does not count inside
转化为. Raw substring counts would credit 化为 with every 转化为 and 简化为.

Only counts leave the text. The output lists the words that occur at least
once: word<TAB>count.

usage: count_general_word_frequency.py --dictionary dict_clean_sc.txt
           --dictionary-tc dict_clean_tc.txt --input <text | archive.zip!member> [...]
           --output manifests/general_word_counts.tsv [--rg rg]
"""

from __future__ import annotations

import argparse
import collections
import pathlib
import subprocess
import tempfile
import threading
import zipfile

import opencc


def dictionary_words(path: pathlib.Path) -> set[str]:
    words = set()
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        fields = line.split("\t")
        if len(fields) >= 3 and len(fields[1]) >= 2:
            words.add(fields[1])
    return words


def feed(source_name: str, stdin) -> None:
    """Stream a text file, or a member of a zip archive (archive.zip!member), to ripgrep."""
    try:
        if "!" in source_name:
            archive_path, member = source_name.split("!", 1)
            with zipfile.ZipFile(archive_path) as archive, archive.open(member) as source:
                while chunk := source.read(1 << 22):
                    stdin.write(chunk)
        else:
            with open(source_name, "rb") as source:
                while chunk := source.read(1 << 22):
                    stdin.write(chunk)
    finally:
        stdin.close()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dictionary", required=True, type=pathlib.Path)
    parser.add_argument("--dictionary-tc", required=True, type=pathlib.Path)
    parser.add_argument("--input", action="append", required=True)
    parser.add_argument("--output", required=True, type=pathlib.Path)
    parser.add_argument("--rg", default="rg")
    args = parser.parse_args()

    to_simplified = opencc.OpenCC("tw2s")
    words = dictionary_words(args.dictionary)
    words |= {to_simplified.convert(word) for word in dictionary_words(args.dictionary_tc)}
    counts: collections.Counter[str] = collections.Counter()
    with tempfile.TemporaryDirectory() as scratch:
        patterns = pathlib.Path(scratch) / "patterns.txt"
        patterns.write_text("\n".join(sorted(words, key=lambda w: (-len(w), w))) + "\n", encoding="utf-8")
        print(f"{len(words)} patterns", flush=True)
        for path in args.input:
            rg = subprocess.Popen([args.rg, "-a", "-o", "-F", "--no-filename", "--no-line-number",
                                   "-f", str(patterns), "-"], stdin=subprocess.PIPE, stdout=subprocess.PIPE)
            writer = threading.Thread(target=feed, args=(path, rg.stdin))
            writer.start()
            for line in rg.stdout:
                counts[line.decode("utf-8").strip()] += 1
            writer.join()
            if rg.wait() not in (0, 1):
                raise SystemExit(f"ripgrep failed on {path}")
            print(f"{path}: done", flush=True)
    with args.output.open("w", encoding="utf-8", newline="\n") as out:
        out.write("# word\tcount\n")
        out.write("# Occurrences as a word (longest dictionary match first) in the general text of the\n")
        sources = ", ".join(pathlib.PurePath(name.split("!")[-1]).name for name in args.input)
        out.write("# Cassotis character LM: " + sources + ".\n")
        out.write("# Generated by scripts/count_general_word_frequency.py; counts only.\n")
        for word in sorted(w for w in words if counts[w]):
            out.write(f"{word}\t{counts[word]}\n")


if __name__ == "__main__":
    main()
