class DailyReweightImportWordsTests(unittest.TestCase):
    def test_block(self):
        forced = block(HEADER_FORCED)
        self.assertEqual({"exact_rank"}, {row[4] for row in forced})
        self.assertEqual(FORCED, {(row[0], row[1]): row[3] for row in forced})
        self.assertEqual(FORCED_TC, {(row[0], row[2]): row[3] for row in forced})

    def test_no_import_row_left(self):
        text = (ROOT / "manifests/curated_daily_supplement_phrases.tsv").read_text(encoding="utf-8")
        for (pinyin, word), _weight in FORCED.items():
            self.assertFalse([line for line in text.splitlines()
                              if line.split("\t")[0] == word and line.split("\t")[2:3] == ["0.01"]
                              and line.split("\t")[3:4] in ([], [pinyin])], word)

    def test_generated_weights(self):
        for expected, variant in ((FORCED, "sc"), (FORCED_TC, "tc")):
            rows = read_rows(f"dict_clean_{variant}.txt")
            for key, weight in expected.items():
                self.assertEqual(str(weight), rows[key][0], key)

    def test_no_tie_on_a_key(self):
        by_key = {}
        for (pinyin, text), fields in read_rows("dict_clean_sc.txt").items():
            by_key.setdefault(pinyin, {})[text] = int(fields[0])
        for (pinyin, word), weight in FORCED.items():
            others = [text for text, value in by_key[pinyin].items() if text != word and value == weight]
            self.assertFalse(others, (pinyin, word))

    def test_examples_lead_their_key(self):
        rows = read_rows("dict_clean_sc.txt")
        for pinyin, word, other in (("fangkong", "防控", "放空"), ("yezhu", "业主", "噎住"),
                                    ("bianhao", "编号", "变好"), ("paidui", "排队", "派对")):
            self.assertGreater(int(rows[(pinyin, word)][0]), int(rows[(pinyin, other)][0]), word)


