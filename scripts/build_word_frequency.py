#!/usr/bin/env python3
"""Write the word-frequency table a dictionary variant imports.

Every word of the dictionary (two characters or more) that the general text
holds gets a score of 100 * log10(1 + occurrences), rounded: 300 for a
thousand occurrences, 600 for a million. A traditional word takes the count
of its simplified form. The IME reads the score where nothing but the
dictionary decides between words of one reading (the short-word choice
without a context); a word the counts lack has none.

usage: build_word_frequency.py --counts manifests/general_word_counts.tsv
           --dictionary data/generated/dict_clean_sc.txt
           --output data/generated/dict_word_frequency_sc.txt [--traditional]
"""

from __future__ import annotations

import argparse
import math
import pathlib

import opencc


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--counts", required=True, type=pathlib.Path)
    parser.add_argument("--dictionary", required=True, type=pathlib.Path)
    parser.add_argument("--output", required=True, type=pathlib.Path)
    parser.add_argument("--traditional", action="store_true")
    args = parser.parse_args()

    counts = {}
    for line in args.counts.read_text(encoding="utf-8").splitlines():
        if line and not line.startswith("#"):
            word, count = line.split("\t")
            counts[word] = int(count)
    to_simplified = opencc.OpenCC("tw2s") if args.traditional else None
    scores = {}
    for line in args.dictionary.read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        fields = line.split("\t")
        if len(fields) < 3 or len(fields[1]) < 2 or fields[1] in scores:
            continue
        word = fields[1]
        count = counts.get(to_simplified.convert(word) if to_simplified else word, 0)
        if count > 0:
            scores[word] = round(100.0 * math.log10(1 + count))
    with args.output.open("w", encoding="utf-8", newline="\n") as out:
        out.write("# text\tscore\n")
        out.write("# score = round(100 * log10(1 + occurrences as a word in general text)), "
                  "from manifests/general_word_counts.tsv\n")
        out.write("# Generated by scripts/build_word_frequency.py.\n")
        for word in sorted(scores):
            out.write(f"{word}\t{scores[word]}\n")
    print(f"{args.output.name}: {len(scores)} words")


if __name__ == "__main__":
    main()
