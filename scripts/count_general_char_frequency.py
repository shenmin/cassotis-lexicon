#!/usr/bin/env python3
"""Count how often each Chinese character occurs in general Chinese text.

The input is plain UTF-8 text, a file or a member of a zip archive written
archive.zip!member: Cassotis IME uses the general text its character LM was
trained on (the three general corpora, not its fiction), as
count_general_word_frequency.py does. Every character counts, inside a word or
not; build_single_char_frequency.py takes the occurrences inside dictionary
words (manifests/general_word_counts.tsv) off to find how often a character
stands alone.

Only counts leave the text. The output lists the characters of the CJK blocks
that occur at least once: character<TAB>count.

usage: count_general_char_frequency.py --input <text | archive.zip!member> [...]
           --output manifests/general_char_counts.tsv
"""

from __future__ import annotations

import argparse
import codecs
import collections
import pathlib
import re
import zipfile

CJK_RE = re.compile("[㐀-䶿一-鿿豈-﫿\U00020000-\U0003134f]")


def chunks(source_name: str):
    """The text of a file, or of a member of a zip archive, in pieces."""
    decoder = codecs.getincrementaldecoder("utf-8")(errors="replace")
    if "!" in source_name:
        archive_path, member = source_name.split("!", 1)
        with zipfile.ZipFile(archive_path) as archive, archive.open(member) as source:
            while chunk := source.read(1 << 24):
                yield decoder.decode(chunk)
    else:
        with open(source_name, "rb") as source:
            while chunk := source.read(1 << 24):
                yield decoder.decode(chunk)
    yield decoder.decode(b"", final=True)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--input", action="append", required=True)
    parser.add_argument("--output", required=True, type=pathlib.Path)
    args = parser.parse_args()

    counts: collections.Counter[str] = collections.Counter()
    for path in args.input:
        for text in chunks(path):
            counts.update(text)
        print(f"{path}: done", flush=True)
    with args.output.open("w", encoding="utf-8", newline="\n") as out:
        out.write("# character\tcount\n")
        out.write("# Occurrences of each character in the general text of the Cassotis character LM:\n")
        sources = ", ".join(pathlib.PurePath(name.split("!")[-1]).name for name in args.input)
        out.write("# " + sources + ".\n")
        out.write("# Generated by scripts/count_general_char_frequency.py; counts only.\n")
        for char in sorted(c for c in counts if CJK_RE.fullmatch(c)):
            out.write(f"{char}\t{counts[char]}\n")


if __name__ == "__main__":
    main()
